function openSection(role: RoleId): GuideSection {
  const isHq = role === 'hq';
  return {
    id: 'open',
    title: 'アプリを開く',
    body: (
      <>
        <p>
          {isHq
            ? '本部のログインURLを開きます。店舗のURLとは別のものです。'
            : 'ログインURLは店舗ごとに違います。自分の店舗のURLは、店頭に貼られたQRコードか、店舗管理者から配られたリンクで開いてください。'}
        </p>
        <p>
          インストールは要りません。ブラウザで開いたあと、ホーム画面に追加しておくと次から一発で開けます。
        </p>
        <Ul items={[
          <>iPhone：Safariの共有ボタン → <Ui>ホーム画面に追加</Ui></>,
          <>Android：ブラウザのメニュー → <Ui>ホーム画面に追加</Ui></>,
        ]} />
        {isHq && (
          <Caution>
            本部のURLは店舗に配らないでください。店舗のログイン画面の名前一覧に本部管理者は出ませんが、
            画面の下にある<Ui>本部管理者の方はこちら</Ui>から本部のログイン画面へ移動できます。
          </Caution>
        )}
      </>
    ),
  };
}

