/**
 * 詳しい使い方の本文。
 *
 * 構成のきまり（3つの役割すべてで同じ）:
 *   A さいしょに1回だけ … 2回目からは読まなくてよいこと
 *   B 毎月やること       … 毎月かならず通る操作。すべて番号つきの手順で書く
 *   C ときどきやること   … 起きたときだけ読む操作
 *   D 困ったとき         … 症状から引く。手順は書かず、B・C を見てもらう
 *   E 早見表             … 読むのではなく見るもの
 *
 * 書き方のきまり:
 *   - 他の役割のページを読まないと分からない書き方をしない。必要なことは各ページに全部書く
 *   - 「なぜそう作ったか」は書かない。何ができて、どう操作するかだけを書く
 *   - 特定の店舗の名前・URL・時間帯を書かない
 *   - 見出しが「〜する」なら中身は番号つきの手順。名詞の見出しなら説明か表
 */

